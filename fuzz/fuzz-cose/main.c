int
LLVMFuzzerInitialize(int *argc, char ***argv)
{
	struct lws_context_creation_info info;

	(void)argc;
	(void)argv;

	if (!getenv("LWS_FUZZ_VERBOSE"))
		lws_set_log_level(0, NULL);

	memset(&info, 0, sizeof(info));
	info.port = CONTEXT_PORT_NO_LISTEN;
	info.options = LWS_SERVER_OPTION_EXPLICIT_VHOSTS;

	cx = lws_create_context(&info);

	return cx ? 0 : 1;
}

static int
key_cb(struct lws_cose_key *s, void *user)
{
	(void)s;
	(void)user;

	return 0;
}

int
LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
	struct lws_cose_validate_context *cps;
	lws_cose_validate_create_info_t info;
	lws_dll2_owner_t set;
	lws_cose_key_t *ck;
	size_t len, half, used;

	if (size < 2)
		return 0;

	len = size - 2;
	half = len / 2;

	if (!(data[0] & 1)) {
		/* import as a set (array) or a single key */

		lws_dll2_owner_clear(&set);
		lws_cose_key_import(&set, key_cb, NULL, data + 2, len);
		lws_cose_key_set_destroy(&set);

		ck = lws_cose_key_import(NULL, NULL, NULL, data + 2, len);
		if (ck)
			lws_cose_key_destroy(&ck);

		return 0;
	}

	/* validate against the fixed key set */

	lws_dll2_owner_clear(&set);
	if (!lws_cose_key_import(&set, NULL, NULL, keyset1, sizeof(keyset1)))
		return 0;

	memset(&info, 0, sizeof(info));
	info.cx = cx;
	info.keyset = &set;
	info.sigtype = (enum lws_cose_sig_types)(data[1] % 6);

	cps = lws_cose_validate_create(&info);
	if (cps) {
		if (!lws_cose_validate_chunk(cps, data + 2, half, &used))
			lws_cose_validate_chunk(cps, data + 2 + half,
						len - half, &used);
		lws_cose_validate_results(cps);
		lws_cose_validate_destroy(&cps);
	}

	lws_cose_key_set_destroy(&set);

	return 0;
}
