/*
 * F-045 fence: ctx liveness rules.  create() and new_keypair() over a ctx
 * that still holds a live key incarnation must fail cleanly; after
 * destroy(), the same ctx can be recreated and operates with the new key
 *
 * The probes use the sign / verify apis, which every backend this fence
 * runs on provides
 */
static int
test_genrsa_recreate(struct lws_context *context)
{
	static const uint8_t plain_a[] = "recreate roundtrip A";
	static const uint8_t plain_b[] = "recreate roundtrip B";
	struct lws_genrsa_ctx ctx, ctx2, pub1, pub2;
	struct lws_gencrypto_keyelem el[2][LWS_GENCRYPTO_RSA_KEYEL_COUNT];
	struct lws_gencrypto_keyelem pub_el[2][LWS_GENCRYPTO_RSA_KEYEL_COUNT];
	struct lws_gencrypto_keyelem gen[LWS_GENCRYPTO_RSA_KEYEL_COUNT];
	uint8_t hash[32], sig[512];
	int n, ret = 1;

	memset(&ctx, 0, sizeof(ctx));
	memset(&ctx2, 0, sizeof(ctx2));
	memset(&pub1, 0, sizeof(pub1));
	memset(&pub2, 0, sizeof(pub2));
	memset(el, 0, sizeof(el));
	memset(pub_el, 0, sizeof(pub_el));
	memset(gen, 0, sizeof(gen));

	/* two independent keypairs, in two live ctxs */

	if (lws_genrsa_new_keypair(context, &ctx, LGRSAM_PKCS1_1_5, el[0],
				   2048)) {
		lwsl_err("%s: new_keypair 0 failed\n", __func__);
		goto bail;
	}

	if (lws_genrsa_new_keypair(context, &ctx2, LGRSAM_PKCS1_1_5, el[1],
				   2048)) {
		lwsl_err("%s: new_keypair 1 failed\n", __func__);
		goto bail;
	}

	test_genrsa_prepare_public_elements(pub_el[0], el[0]);
	test_genrsa_prepare_public_elements(pub_el[1], el[1]);

	if (lws_genrsa_create(&pub1, pub_el[0], context, LGRSAM_PKCS1_1_5,
			      LWS_GENHASH_TYPE_UNKNOWN) ||
	    lws_genrsa_create(&pub2, pub_el[1], context, LGRSAM_PKCS1_1_5,
			      LWS_GENHASH_TYPE_UNKNOWN)) {
		lwsl_err("%s: pub ctx create failed\n", __func__);
		goto bail;
	}

	/* sanity: ctx currently operates with key 0 */

	if (test_genrsa_hash32(plain_a, sizeof(plain_a) - 1, hash)) {
		lwsl_err("%s: hash failed\n", __func__);
		goto bail;
	}

	n = lws_genrsa_hash_sign(&ctx, hash, LWS_GENHASH_TYPE_SHA256,
				 sig, sizeof(sig));
	if (n < 0) {
		lwsl_err("%s: sign sanity failed\n", __func__);
		goto bail;
	}

	if (lws_genrsa_hash_sig_verify(&pub1, hash,
				       LWS_GENHASH_TYPE_SHA256,
				       sig, (size_t)n)) {
		lwsl_err("%s: sanity sign/verify mismatch\n", __func__);
		goto bail;
	}

	/*
	 * create() over the live ctx must fail; after destroy(), the same ctx
	 * can be recreated with key 1's elements
	 */

	if (!lws_genrsa_create(&ctx, el[1], context, LGRSAM_PKCS1_1_5,
			       LWS_GENHASH_TYPE_UNKNOWN)) {
		lwsl_err("%s: create over live ctx accepted\n", __func__);
		goto bail;
	}

	lws_genrsa_destroy(&ctx);

	if (lws_genrsa_create(&ctx, el[1], context, LGRSAM_PKCS1_1_5,
			      LWS_GENHASH_TYPE_UNKNOWN)) {
		lwsl_err("%s: recreate after destroy failed\n", __func__);
		goto bail;
	}

	if (test_genrsa_hash32(plain_b, sizeof(plain_b) - 1, hash)) {
		lwsl_err("%s: hash failed\n", __func__);
		goto bail;
	}

	n = lws_genrsa_hash_sign(&ctx, hash, LWS_GENHASH_TYPE_SHA256,
				 sig, sizeof(sig));
	if (n < 0) {
		lwsl_err("%s: sign after recreate failed\n", __func__);
		goto bail;
	}

	if (lws_genrsa_hash_sig_verify(&pub2, hash,
				       LWS_GENHASH_TYPE_SHA256,
				       sig, (size_t)n)) {
		lwsl_err("%s: recreated ctx not operating with key 1\n",
			 __func__);
		goto bail;
	}

	/* ...and it must no longer be operating with key 0 */

	if (!lws_genrsa_hash_sig_verify(&pub1, hash,
					LWS_GENHASH_TYPE_SHA256,
					sig, (size_t)n)) {
		lwsl_err("%s: recreated ctx still operating with key 0\n",
			 __func__);
		goto bail;
	}

	/* destroy + recreate again restores key 0 */

	lws_genrsa_destroy(&ctx);

	if (lws_genrsa_create(&ctx, el[0], context, LGRSAM_PKCS1_1_5,
			      LWS_GENHASH_TYPE_UNKNOWN)) {
		lwsl_err("%s: recreate with key 0 failed\n", __func__);
		goto bail;
	}

	if (test_genrsa_hash32(plain_a, sizeof(plain_a) - 1, hash)) {
		lwsl_err("%s: hash failed\n", __func__);
		goto bail;
	}

	n = lws_genrsa_hash_sign(&ctx, hash, LWS_GENHASH_TYPE_SHA256,
				 sig, sizeof(sig));
	if (n < 0) {
		lwsl_err("%s: sign after second recreate failed\n",
			 __func__);
		goto bail;
	}

	if (lws_genrsa_hash_sig_verify(&pub1, hash,
				       LWS_GENHASH_TYPE_SHA256,
				       sig, (size_t)n)) {
		lwsl_err("%s: second recreate sign/verify mismatch\n",
			 __func__);
		goto bail;
	}

	/*
	 * new_keypair() over the live keyed ctx must fail too; after
	 * destroy() it generates a fresh key into the same ctx
	 */

	if (!lws_genrsa_new_keypair(context, &ctx, LGRSAM_PKCS1_1_5, gen,
				    2048)) {
		lwsl_err("%s: new_keypair over live ctx accepted\n", __func__);
		goto bail;
	}

	lws_genrsa_destroy(&ctx);

	if (lws_genrsa_new_keypair(context, &ctx, LGRSAM_PKCS1_1_5, gen,
				   2048)) {
		lwsl_err("%s: new_keypair after destroy failed\n", __func__);
		goto bail;
	}

	ret = 0;

bail:
	lws_genrsa_destroy(&pub2);
	lws_genrsa_destroy(&pub1);
	lws_genrsa_destroy(&ctx2);
	lws_genrsa_destroy(&ctx);
	lws_genrsa_destroy_elements(el[0]);
	lws_genrsa_destroy_elements(el[1]);
	lws_genrsa_destroy_elements(gen);

	return ret;
}
