static int
test_genrsa_pss_hash(enum lws_genhash_types type, const void *in, size_t len,
		     uint8_t *hash)
{
	struct lws_genhash_ctx gh;

	if (lws_genhash_init(&gh, type) ||
	    lws_genhash_update(&gh, in, len) ||
	    lws_genhash_destroy(&gh, hash))
		return 1;

	return 0;
}

static int
test_genrsa_pss(struct lws_context *context)
{
	struct lws_gencrypto_keyelem priv[LWS_GENCRYPTO_RSA_KEYEL_COUNT];
	struct lws_gencrypto_keyelem pub[LWS_GENCRYPTO_RSA_KEYEL_COUNT];
	uint8_t hash[LWS_GENHASH_LARGEST], sig[sizeof(genrsa_pss_n)];
	struct lws_genrsa_ctx priv_ctx, pub_ctx;
	size_t i, msg_len = strlen(genrsa_pss_msg);
	int n, ret = 1;

	memset(&priv_ctx, 0, sizeof(priv_ctx));
	memset(&pub_ctx, 0, sizeof(pub_ctx));
	memset(priv, 0, sizeof(priv));
	memset(pub, 0, sizeof(pub));

#define genrsa_pss_el(_idx, _arr) \
	priv[_idx].buf = (uint8_t *)(uintptr_t)_arr; \
	priv[_idx].len = (uint32_t)sizeof(_arr)

	genrsa_pss_el(LWS_GENCRYPTO_RSA_KEYEL_E,  genrsa_pss_e);
	genrsa_pss_el(LWS_GENCRYPTO_RSA_KEYEL_N,  genrsa_pss_n);
	genrsa_pss_el(LWS_GENCRYPTO_RSA_KEYEL_D,  genrsa_pss_d);
	genrsa_pss_el(LWS_GENCRYPTO_RSA_KEYEL_P,  genrsa_pss_p);
	genrsa_pss_el(LWS_GENCRYPTO_RSA_KEYEL_Q,  genrsa_pss_q);
	genrsa_pss_el(LWS_GENCRYPTO_RSA_KEYEL_DP, genrsa_pss_dp);
	genrsa_pss_el(LWS_GENCRYPTO_RSA_KEYEL_DQ, genrsa_pss_dq);
	genrsa_pss_el(LWS_GENCRYPTO_RSA_KEYEL_QI, genrsa_pss_qi);

#undef genrsa_pss_el

	test_genrsa_prepare_public_elements(pub, priv);

	for (i = 0; i < LWS_ARRAY_SIZE(genrsa_pss_algs); i++) {
		enum lws_genhash_types ht = genrsa_pss_algs[i].hash;
		const char *nm = genrsa_pss_algs[i].name;

		if (lws_genrsa_create(&priv_ctx, priv, context,
				      LGRSAM_PKCS1_OAEP_PSS,
				      LWS_GENHASH_TYPE_UNKNOWN) ||
		    lws_genrsa_create(&pub_ctx, pub, context,
				      LGRSAM_PKCS1_OAEP_PSS,
				      LWS_GENHASH_TYPE_UNKNOWN)) {
			lwsl_err("%s: %s: lws_genrsa_create failed\n",
				 __func__, nm);
			goto bail;
		}

		if (test_genrsa_pss_hash(ht, genrsa_pss_msg, msg_len, hash)) {
			lwsl_err("%s: %s: hash failed\n", __func__, nm);
			goto bail;
		}

		/* 1) sign with the private key, verify with the public one */

		n = lws_genrsa_hash_sign(&priv_ctx, hash, ht, sig, sizeof(sig));
		if (n < 0) {
			lwsl_err("%s: %s: sign failed\n", __func__, nm);
			goto bail;
		}

		if (lws_genrsa_hash_sig_verify(&pub_ctx, hash, ht, sig,
					       (size_t)n)) {
			lwsl_err("%s: %s: verify of our own signature failed\n",
				 __func__, nm);
			goto bail;
		}

		/* 2) a signature over the same key and message made elsewhere */

		if (lws_genrsa_hash_sig_verify(&pub_ctx, hash, ht,
					       genrsa_pss_algs[i].sig,
					       genrsa_pss_algs[i].sig_len)) {
			lwsl_err("%s: %s: known-good PSS vector rejected\n",
				 __func__, nm);
			goto bail;
		}

		/*
		 * 3) the same key and message signed PKCS#1 v1.5 with SHA-256
		 *    must not be accepted as a PSS signature (it is only a
		 *    SHA-256 signature, so it can only be offered to PS256)
		 */

		if (ht == LWS_GENHASH_TYPE_SHA256 &&
		    !lws_genrsa_hash_sig_verify(&pub_ctx, hash, ht,
						genrsa_pss_v15_sha256,
						sizeof(genrsa_pss_v15_sha256))) {
			lwsl_err("%s: %s: PKCS#1 v1.5 signature accepted as "
				 "PSS\n", __func__, nm);
			goto bail;
		}

		lws_genrsa_destroy(&pub_ctx);
		lws_genrsa_destroy(&priv_ctx);

		lwsl_info("%s: %s OK\n", __func__, nm);
	}

	ret = 0;

bail:
	lws_genrsa_destroy(&pub_ctx);
	lws_genrsa_destroy(&priv_ctx);

	return ret;
}

int
test_genrsa(struct lws_context *context)
{
#if !defined(GENRSA_HAS_PKCS1_DATAOPS) && !defined(GENRSA_HAS_OAEP) && \
    !defined(GENRSA_HAS_KEYGEN_SIGNVERIFY)
	lwsl_notice("%s: Skipping RSA data-op tests (unsupported on this "
		    "backend)\n", __func__);
#else
#if defined(GENRSA_HAS_PKCS1_DATAOPS)
	if (test_genrsa_roundtrips(context))
		goto bail;

	if (test_genrsa_fixed_vectors(context))
		goto bail;
#endif

#if defined(GENRSA_HAS_OAEP)
	if (test_genrsa_oaep_roundtrips(context))
		goto bail;
#endif

#if defined(GENRSA_HAS_KEYGEN_SIGNVERIFY)
	if (test_genrsa_recreate(context))
		goto bail;
#endif
#endif

	/* every backend must do RSA-PSS, it is what JWS PS256/384/512 is */

	if (test_genrsa_pss(context))
		goto bail;

	lwsl_notice("%s: selftest OK\n", __func__);

	return 0;

bail:
	lwsl_err("%s: selftest failed ++++++++++++++++++++\n", __func__);

	return 1;
}
